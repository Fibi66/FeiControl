#!/usr/bin/env node
/**
 * Generate `public/memory-graph-demo.json` — a fully synthetic memory graph.
 *
 * Why this exists
 * ---------------
 * `public/memory-graph-data.json` is a *runtime artifact*: the Memory Graph
 * server (`src/lib/memory-graph/graph-server.ts`) rebuilds it from the local
 * OpenClaw workspace, and it therefore contains the operator's real agent names,
 * note titles and excerpts. It is git-ignored and must never be committed.
 *
 * A fresh clone has no OpenClaw workspace, so the graph would render empty.
 * This script produces a fake-but-realistic dataset that the API falls back to,
 * so the feature is browsable out of the box without leaking anyone's data.
 *
 * Usage:  node scripts/make-demo-graph.mjs
 * Output: public/memory-graph-demo.json
 */
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'public', 'memory-graph-demo.json');

// Deterministic PRNG (mulberry32) so the demo file is reproducible.
function makeRng(seed) {
  let a = seed >>> 0;
  return function rng() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const AGENTS = [
  { id: 'atlas', color: '#3B82F6' },
  { id: 'nova', color: '#A855F7' },
  { id: 'scribe', color: '#22C55E' },
  { id: 'scout', color: '#F97316' },
];

const DOCS = [
  ['AGENTS.md', 'Working agreement for the demo workspace'],
  ['MEMORY.md', 'Long-term notes and decisions'],
  ['SOUL.md', 'Persona and behaviour guidelines'],
  ['USER.md', 'Profile of the operator'],
  ['TOOLS.md', 'Available tooling and conventions'],
  ['ARCHITECTURE.md', 'How the agent memory layer is structured'],
  ['ROADMAP.md', 'Planned work, by priority'],
];

const THEMES = [
  'session cleanup', 'cost tracking', 'cron scheduling', 'memory distillation',
  'tool permissions', 'log rotation', 'agent handoff', 'snapshot backup',
  'search indexing', 'prompt caching',
];

const WIKI = [
  ['retrieval', 'Retrieval-augmented generation notes'],
  ['vector-store', 'Embedding store trade-offs'],
  ['evaluation', 'How we evaluate answer quality'],
];

const TYPES = ['doc', 'daily', 'deep', 'light', 'rem', 'wiki'];

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

function isoDate(d) {
  return d.toISOString().slice(0, 10);
}

function build() {
  const rng = makeRng(20261004);
  const nodes = [];
  const edges = [];
  let seq = 0;

  const push = (agent, type, title, relPath, date, snippet) => {
    const meta = AGENTS.find((a) => a.id === agent);
    const node = {
      id: `d${seq++}`,
      title,
      agent,
      type,
      date,
      path: relPath,
      snippet,
      size: 400 + Math.floor(rng() * 9000),
      color: meta.color,
      degree: 0,
      workspace: type === 'wiki' ? 'wiki' : 'workspace',
    };
    nodes.push(node);
    return node;
  };

  // --- Shared docs, owned by the first agent (root-level notes) ------------
  const docNodes = DOCS.map(([file, blurb]) =>
    push('atlas', 'doc', `${file} - ${blurb}`, file, '2026-09-18',
      `${blurb}. This is demo content generated by scripts/make-demo-graph.mjs — it does not describe any real system.`)
  );

  // --- Wiki pages ----------------------------------------------------------
  const wikiNodes = WIKI.map(([slug, blurb]) =>
    push('nova', 'wiki', `${slug} - ${blurb}`, `wiki/${slug}.md`, '2026-09-20',
      `${blurb}. Demo entry.`)
  );

  // --- Per-agent memory over ~30 days -------------------------------------
  const today = new Date('2026-10-04T00:00:00Z');
  for (const agent of AGENTS) {
    for (let dayOffset = 29; dayOffset >= 0; dayOffset--) {
      const d = new Date(today);
      d.setUTCDate(d.getUTCDate() - dayOffset);
      const date = isoDate(d);
      const theme = pick(rng, THEMES);

      // every day has a "daily" note
      const daily = push(
        agent.id, 'daily', `${agent.id} daily ${date}`,
        `memory/${date}.md`, date,
        `Daily log for ${agent.id} on ${date}. Focus: ${theme}. Demo entry.`
      );

      // occasionally deeper / lighter notes
      if (rng() < 0.45) {
        const t = rng() < 0.5 ? 'deep' : 'light';
        const extra = push(
          agent.id, t, `${agent.id} ${theme} (${t})`,
          `memory/${date}-${theme.replace(/\s+/g, '-')}.md`, date,
          `Extended note about ${theme}. Demo entry.`
        );
        edges.push({ s: daily.id, t: extra.id, k: 'timeline' });
      }

      // reminders
      if (rng() < 0.3) {
        const rem = push(
          agent.id, 'rem', `${agent.id} reminder: ${theme}`,
          `memory/reminders/${date}.md`, date,
          `Reminder to follow up on ${theme}. Demo entry.`
        );
        edges.push({ s: daily.id, t: rem.id, k: 'evidence' });
      }
    }
  }

  // --- Evidence edges: notes citing the shared docs -----------------------
  for (const n of nodes) {
    if (n.type === 'doc' || n.type === 'wiki') continue;
    if (rng() < 0.35) edges.push({ s: n.id, t: pick(rng, docNodes).id, k: 'evidence' });
    if (rng() < 0.2) edges.push({ s: n.id, t: pick(rng, wikiNodes).id, k: 'evidence' });
  }

  // --- Timeline edges: consecutive daily notes of the same agent ----------
  for (const agent of AGENTS) {
    const dailies = nodes.filter((n) => n.agent === agent.id && n.type === 'daily');
    for (let i = 1; i < dailies.length; i++) {
      edges.push({ s: dailies[i - 1].id, t: dailies[i].id, k: 'timeline' });
    }
  }

  // Degrees
  const deg = new Map();
  for (const e of edges) {
    deg.set(e.s, (deg.get(e.s) || 0) + 1);
    deg.set(e.t, (deg.get(e.t) || 0) + 1);
  }
  for (const n of nodes) n.degree = deg.get(n.id) || 0;

  const evidence = edges.filter((e) => e.k === 'evidence').length;
  const timeline = edges.filter((e) => e.k === 'timeline').length;

  return {
    generatedAt: new Date().toISOString(),
    source: 'demo dataset (scripts/make-demo-graph.mjs) — no real data',
    demo: true,
    agents: AGENTS.map((a) => ({
      ...a,
      count: nodes.filter((n) => n.agent === a.id).length,
    })),
    stats: {
      nodes: nodes.length,
      evidenceEdges: evidence,
      timelineEdges: timeline,
      linkEdges: 0,
      agents: AGENTS.length,
      fromOpenclaw: 0,
    },
    nodes,
    edges,
  };
}

const data = build();
fs.writeFileSync(OUT, JSON.stringify(data));
console.log(
  `wrote ${path.relative(process.cwd(), OUT)} — ` +
  `${data.stats.nodes} nodes, ${data.stats.evidenceEdges} evidence edges, ` +
  `${data.stats.timelineEdges} timeline edges, ${data.stats.agents} agents`
);
